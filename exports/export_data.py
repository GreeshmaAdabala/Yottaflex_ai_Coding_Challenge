import csv
import json
import sqlite3
from datetime import date, datetime
from pathlib import Path

from database.db import db
from database.models import (
    Allocation,
    AnomalyGroundTruth,
    Availability,
    DemandPlan,
    Employee,
    EmployeeSkill,
    GapAnalysis,
    Project,
    Role,
    RoleSkill,
    Skill,
    Training,
)


CORE_MODELS = [
    Employee,
    Role,
    Skill,
    EmployeeSkill,
    Project,
    DemandPlan,
    Allocation,
    Availability,
    Training,
    GapAnalysis,
]


def _value(value):
    if isinstance(value, (date, datetime)):
        return value.isoformat()
    return value


def _rows(model):
    fields = [column.name for column in model.__table__.columns]
    return fields, [
        {field: _value(getattr(record, field)) for field in fields}
        for record in db.session.query(model).order_by(
            *[getattr(model, key.name) for key in model.__table__.primary_key.columns]
        )
    ]


def export_all(output_dir="exports"):
    root = Path(output_dir)
    csv_dir, json_dir, sql_dir = root / "csv", root / "json", root / "sql"
    for directory in (csv_dir, json_dir, sql_dir):
        directory.mkdir(parents=True, exist_ok=True)

    counts = {}
    for model in CORE_MODELS:
        fields, records = _rows(model)
        name = model.__tablename__
        counts[name] = len(records)
        with (csv_dir / f"{name}.csv").open("w", newline="", encoding="utf-8") as file:
            writer = csv.DictWriter(file, fieldnames=fields)
            writer.writeheader()
            writer.writerows(records)
        with (json_dir / f"{name}.json").open("w", encoding="utf-8") as file:
            json.dump(records, file, indent=2, ensure_ascii=False)

    ground_truth_fields, ground_truth = _rows(AnomalyGroundTruth)
    truth_dir = root.parent / "ground_truth"
    truth_dir.mkdir(parents=True, exist_ok=True)
    with (truth_dir / "ground_truth.csv").open(
        "w", newline="", encoding="utf-8"
    ) as file:
        writer = csv.DictWriter(file, fieldnames=ground_truth_fields)
        writer.writeheader()
        writer.writerows(ground_truth)
    with (truth_dir / "ground_truth.json").open("w", encoding="utf-8") as file:
        json.dump(ground_truth, file, indent=2, ensure_ascii=False)
    with (json_dir / "ground_truth.json").open("w", encoding="utf-8") as file:
        json.dump(ground_truth, file, indent=2, ensure_ascii=False)

    if db.engine.dialect.name != "sqlite":
        raise RuntimeError(
            "The complete SQL data dump is generated from SQLite only; use the local "
            "SQLite database for exports when running against PostgreSQL."
        )
    raw_connection = db.engine.raw_connection()
    try:
        connection = raw_connection.driver_connection
        with (sql_dir / "workforce_dump.sql").open("w", encoding="utf-8") as file:
            for statement in connection.iterdump():
                file.write(statement)
                file.write("\n")
    finally:
        raw_connection.close()

    manifest = [
        "# Generated data source manifest",
        "",
        "- Source: deterministic synthetic data generated by `generator/generate_data.py`.",
        "- Seed: `20261022` by default; generation is configurable.",
        "- Personal data: none; names and organizations are Faker-generated.",
        "- Historical demand: synthetic weekly planned records, not observed production data.",
        "- Ground truth: separately exported labels in `../ground_truth/`.",
        "",
        "## Exported core tables",
        "",
        "| Table | Records |",
        "|---|---:|",
    ]
    manifest.extend(f"| `{table}` | {count:,} |" for table, count in counts.items())
    manifest.extend(
        [
            "",
            "CSV and JSON files are in `csv/` and `json/`. `sql/workforce_dump.sql` is a SQLite schema-and-data dump.",
        ]
    )
    (root / "source_manifest.md").write_text("\n".join(manifest) + "\n", encoding="utf-8")
    return {"counts": counts, "ground_truth": len(ground_truth), "output_dir": str(root)}
